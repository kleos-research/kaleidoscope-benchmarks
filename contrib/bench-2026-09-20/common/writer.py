"""The writer: one LLM call turns a unit of text into the structured delta `remember` requires.

kscope has no model inside it, so something must do this; it is the slot mem0's
own extractor occupies inside `add()`. The prompt is DOMAIN-INDEPENDENT and
byte-identical for every benchmark and split (asserted by `PROMPT_SHA`), and the
contract it carries is read from `kscope schema remember` at run time -- never
transcribed -- so the vocabulary cannot drift from the binary under test.

`content_md` is NOT the model's to write: the adapter stores the unit verbatim,
so the writer can change what is *retrievable* and never what is *said*.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess

from . import kscope_io, llm

CAPS = {"facts": 32, "entities": 32, "propose": 8}

INSTRUCTIONS = """You are writing to a long-term memory store on behalf of an agent. UNIT below is a record the agent wants to keep. Produce the structured delta the store requires, so that a later search can find what this record establishes.

Return ONLY one JSON object, no prose and no code fence:
{"title": "...", "memory_type": "...", "entities": [{"n": "...", "kind": "...", "is": "..."}], "facts": [{"subject": "...", "predicate": "...", "object": "...", "mode": "...", "basis": "..."}], "propose": []}

Rules:
- Record only what UNIT states. Invent nothing.
- At most 32 facts, 32 entities, 8 propose entries. If UNIT holds more, keep the most specific and answer-bearing.
- Every subject and object you use must appear in `entities`, spelled exactly as the fact spells it.
- Reuse a known predicate where one fits. Add a `propose` entry only for a relation none of them covers, and then declare honestly whether one subject may hold several objects at once (`many`).
- `title` is a short description of the content, not a position or a number.
- The store's own contract follows. Where it lists accepted values for a field, use one of them.

=== CONTRACT (generated by the store itself) ===
"""

_schema = None


def schema_text() -> str:
    global _schema
    if _schema is None:
        _schema = subprocess.run([str(kscope_io.KSCOPE), "schema", "remember"],
                                 capture_output=True, text=True).stdout
    return _schema


def system_prompt() -> str:
    return INSTRUCTIONS + schema_text()


def prompt_sha() -> str:
    return hashlib.sha256(system_prompt().encode()).hexdigest()[:16]


def _parse(text: str) -> dict | None:
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text)
    for candidate in (text, text[text.find("{"): text.rfind("}") + 1] if "{" in text else ""):
        if not candidate:
            continue
        try:
            value = json.loads(candidate)
            if isinstance(value, dict):
                return value
        except ValueError:
            # LaTeX inside JSON strings: a lone backslash is the usual break.
            try:
                value = json.loads(re.sub(r'\\(?!["\\/bfnrtu])', r"\\\\", candidate))
                if isinstance(value, dict):
                    return value
            except ValueError:
                continue
    return None


def extract(unit: str, *, effort: str = "high", tag: str = "") -> tuple[dict | None, dict]:
    """Returns (delta_or_None, stats). Two attempts, shape-agnostic parse, then the caller falls back."""
    stats = {"attempts": 0, "parse_failures": 0, "clamped": {}, "prompt_sha": prompt_sha()}
    messages = [{"role": "system", "content": system_prompt()},
                {"role": "user", "content": "UNIT:\n" + unit}]
    for _ in range(2):
        stats["attempts"] += 1
        text, usage = llm.chat(messages, role="writer", effort=effort, max_completion_tokens=12000, tag=tag)
        delta = _parse(text)
        if delta and delta.get("facts"):
            for key, cap in CAPS.items():
                if isinstance(delta.get(key), list) and len(delta[key]) > cap:
                    stats["clamped"][key] = len(delta[key]) - cap
                    delta[key] = delta[key][:cap]
            return delta, stats
        stats["parse_failures"] += 1
        messages = messages[:2] + [{"role": "assistant", "content": text[:2000]},
                                   {"role": "user", "content": "That was not one valid JSON object with a non-empty `facts` list. Return only the JSON object."}]
    return None, stats


def coerce_propose(delta: dict) -> tuple[dict, dict]:
    """Make `propose` satisfy the store's TYPES, changing no meaning.

    `remember` refuses the WHOLE item when one proposal has the wrong shape, and
    that refusal is an `rc=2` body deserialization failure -- so every fact and
    entity the unit had is discarded and only a 1-fact fallback survives.
    Measured 2026-09-20: **7 of 17 MemoryArena chunks carrying a `propose` block
    were refused (41%); 0 of 3 without one.** The same defect cost 2 of 20 units
    in the MemoryAgentBench smoke.

    The mismatch is types only. `propose[].from` and `propose[].to` are the
    declared domain and range KINDS -- sequences -- and the writer sends a bare
    string. `many` is a boolean and the writer sends a word. The prompt's own
    example shows `"propose": []`, so the model infers the shape from contract
    prose that never says "array".

    A scalar domain or range becomes a one-element sequence: same kind, nothing
    added, nothing split. A `many` spelling an unambiguous yes or no becomes that
    boolean. **A `many` with no readable truth value is DROPPED and counted,
    never guessed** -- inventing one would be a claim about what collides on the
    slot key. Facts using that predicate are unaffected; the contract accepts a
    new predicate without a proposal.
    """
    stats = {"wrapped": 0, "booleanised": 0, "dropped": 0}
    proposals = delta.get("propose")
    if not isinstance(proposals, list) or not proposals:
        return delta, stats
    TRUE, FALSE = {"true", "yes", "many", "multi", "multivalued"}, {"false", "no", "one", "single", "singlevalued"}
    kept = []
    for proposal in proposals:
        if not isinstance(proposal, dict):
            stats["dropped"] += 1
            continue
        fixed = dict(proposal)
        for key in ("from", "to"):
            value = fixed.get(key)
            if isinstance(value, str):
                fixed[key] = [value]
                stats["wrapped"] += 1
        many = fixed.get("many")
        if not isinstance(many, bool):
            word = str(many).strip().lower().replace("-", "").replace("_", "").replace(" ", "")
            if word in TRUE or word in FALSE:
                fixed["many"] = word in TRUE
                stats["booleanised"] += 1
            else:
                stats["dropped"] += 1
                continue
        kept.append(fixed)
    delta = dict(delta)
    delta["propose"] = kept
    return delta, stats


def to_item(unit: str, delta: dict) -> dict:
    """The `remember` item: the unit verbatim as content, the model's structure as the delta."""
    semantic = {"memory_type": delta.get("memory_type") or "note",
                "title": (delta.get("title") or unit.strip().splitlines()[0])[:160],
                "facts": delta["facts"]}
    if delta.get("entities"):
        semantic["entities"] = delta["entities"]
    delta, _propose_stats = coerce_propose(delta)
    if delta.get("propose"):
        semantic["propose"] = delta["propose"]
    return {"content_md": unit, "semantic_delta": semantic}
